/**
 * Helper to retrieve SMART description suggestions for any given development activity.
 * Handles variations in colons, case, or spacing.
 */
export const getSmartDescriptionsForActivity = (activityCategory?: string): string[] => {
  if (!activityCategory) return [];
  const clean = activityCategory.replace(/:$/, '').trim();

  // Direct lookup
  if (SMART_DESCRIPTIONS_BY_ACTIVITY[clean]) {
    return SMART_DESCRIPTIONS_BY_ACTIVITY[clean];
  }

  // Case-insensitive lookup
  const foundKey = Object.keys(SMART_DESCRIPTIONS_BY_ACTIVITY).find(
    (k) => k.toLowerCase() === clean.toLowerCase()
  );
  if (foundKey) {
    return SMART_DESCRIPTIONS_BY_ACTIVITY[foundKey];
  }

  return [];
};
